// Autocomplete */
(function($) {
	$.fn.autocomplete = function(option) {
		return this.each(function() {
			this.timer = null;
			this.items = new Array();

			$.extend(this, option);

			$(this).attr('autocomplete', 'off');

			// Focus
			$(this).on('focus', function() {
				this.request();
			});

			// Blur
			$(this).on('blur', function() {
				setTimeout(function(object) {
					object.hide();
				}, 200, this);
			});

			// Keydown
			$(this).on('keydown', function(event) {
				switch(event.keyCode) {
					case 27: // escape
						this.hide();
						break;
					default:
						this.request();
						break;
				}
			});

			// Click
			this.click = function(event) {
				event.preventDefault();

				value = $(event.target).parent().attr('data-value');

				if (value && this.items[value]) {
					this.select(this.items[value]);
				}
			}

			// Show
			this.show = function() {
				var pos = $(this).position();

				$(this).siblings('ul.dropdown-menu').css({
					top: pos.top + $(this).outerHeight(),
					left: pos.left
				});

				$(this).siblings('ul.dropdown-menu').show();
			}

			// Hide
			this.hide = function() {
				$(this).siblings('ul.dropdown-menu').hide();
			}

			// Request
			this.request = function() {
				clearTimeout(this.timer);

				this.timer = setTimeout(function(object) {
					object.source($(object).val(), $.proxy(object.response, object));
				}, 200, this);
			}

			// Response
			this.response = function(json) {
				html = '';

				if (json.length) {
					for (i = 0; i < json.length; i++) {
						this.items[json[i]['value']] = json[i];
					}

					for (i = 0; i < json.length; i++) {
						if (!json[i]['category']) {
							html += '<li data-value="' + json[i]['value'] + '"><a href="#">' + json[i]['label'] + '</a></li>';
						}
					}

					// Get all the ones with a categories
					var category = new Array();

					for (i = 0; i < json.length; i++) {
						if (json[i]['category']) {
							if (!category[json[i]['category']]) {
								category[json[i]['category']] = new Array();
								category[json[i]['category']]['name'] = json[i]['category'];
								category[json[i]['category']]['item'] = new Array();
							}

							category[json[i]['category']]['item'].push(json[i]);
						}
					}

					for (i in category) {
						html += '<li class="dropdown-header">' + category[i]['name'] + '</li>';

						for (j = 0; j < category[i]['item'].length; j++) {
							html += '<li data-value="' + category[i]['item'][j]['value'] + '"><a href="#">&nbsp;&nbsp;&nbsp;' + category[i]['item'][j]['label'] + '</a></li>';
						}
					}
				}

				if (html) {
					this.show();
				} else {
					this.hide();
				}

				$(this).siblings('ul.dropdown-menu').html(html);
			}

			$(this).after('<ul class="dropdown-menu"></ul>');
			$(this).siblings('ul.dropdown-menu').delegate('a', 'click', $.proxy(this.click, this));

		});
	}
})(window.jQuery);

/* ==========================================================================
   Storefront Recommendation Carousel Navigation
   ========================================================================== */
function initCarousels() {
  document.querySelectorAll('.carousel-nav-btn').forEach(function(btn) {
    btn.addEventListener('click', function(e) {
      e.preventDefault();
      var targetSelector = this.getAttribute('data-target');
      var container = document.querySelector(targetSelector);
      if (!container) return;

      var card = container.querySelector('.carousel-card-item');
      var scrollAmount = card ? (card.offsetWidth + 20) * 2 : 450;

      if (this.classList.contains('btn-prev')) {
        container.scrollBy({ left: -scrollAmount, behavior: 'smooth' });
      } else {
        container.scrollBy({ left: scrollAmount, behavior: 'smooth' });
      }
    });
  });

  document.querySelectorAll('.recommendation-scroll-strip').forEach(function(strip) {
    function updateChevronState() {
      var section = strip.closest('.storefront-carousel-section');
      if (!section) return;
      var prevBtn = section.querySelector('.carousel-nav-btn.btn-prev');
      var nextBtn = section.querySelector('.carousel-nav-btn.btn-next');
      if (!prevBtn || !nextBtn) return;

      var maxScroll = strip.scrollWidth - strip.clientWidth;
      prevBtn.disabled = strip.scrollLeft <= 5;
      nextBtn.disabled = strip.scrollLeft >= maxScroll - 5;
    }

    strip.addEventListener('scroll', updateChevronState, { passive: true });
    updateChevronState();
    window.addEventListener('resize', updateChevronState);
  });
}

/* ==========================================================================
   Google AI Mode Similar Records Modal Controller
   ========================================================================== */
function openAiModal(productId) {
  var modal = document.getElementById('aiSimilarModal');
  var content = document.getElementById('aiSimilarModalContent');
  if (!modal || !content) return;

  modal.style.display = 'flex';
  document.body.style.overflow = 'hidden';

  content.innerHTML = '<div class="ai-modal-loader">' +
    '<div class="ai-loader-spinner"></div>' +
    '<p>Analyzing acoustic characteristics and finding similar releases...</p>' +
    '</div>';

  fetch('index.php?route=product/product/similar&product_id=' + encodeURIComponent(productId) + '&format=json', {
    headers: { 'X-Requested-With': 'XMLHttpRequest' }
  })
  .then(function(res) { return res.json(); })
  .then(function(data) {
    if (data.success && data.products && data.products.length) {
      var html = '<div class="ai-modal-results-meta" style="margin-bottom: 16px; font-size: 13px; color: #64748B;">' +
        'Releases acoustically and taxonomically matching <strong>' + (data.current.name || '') + '</strong>' +
        '</div>';

      html += '<div class="ai-similar-grid">';
      data.products.forEach(function(prod) {
        html += '<div class="vinyl-card" style="padding: 10px;">' +
          '<div class="vinyl-card__cover-wrap" style="margin-bottom: 8px;">' +
            '<a href="' + prod.href + '">' +
              '<img src="' + prod.thumb + '" alt="' + prod.name + '" class="vinyl-card__artwork" />' +
            '</a>' +
            (prod.format_badge ? '<span class="vinyl-card__format-badge ' + (prod.format_badge === 'Audio CD' ? 'badge-cd' : 'badge-vinyl') + '">' + prod.format_badge + '</span>' : '') +
          '</div>' +
          '<div class="vinyl-card__meta-content">' +
            '<div class="vinyl-card__line-artist">' + prod.artist + '</div>' +
            '<div class="vinyl-card__line-title"><a href="' + prod.href + '">' + prod.name + '</a></div>' +
            '<div class="vinyl-card__line-submeta">' + prod.meta + '</div>' +
            '<div class="vinyl-card__line-action">' +
              '<span class="vinyl-card__price">' + prod.price + '</span>' +
              '<button type="button" class="btn-vinyl-cart" onclick="cart.add(\'' + prod.product_id + '\', 1);" title="Add to Cart">' +
                '<i class="fa fa-shopping-cart"></i>' +
              '</button>' +
            '</div>' +
          '</div>' +
        '</div>';
      });
      html += '</div>';
      content.innerHTML = html;
    } else {
      content.innerHTML = '<div style="text-align: center; padding: 30px; color: #64748B;">' +
        '<p>No direct similar releases found in catalog for this item.</p>' +
        '<a href="index.php?route=product/search" class="btn btn-primary btn-sm">Search Full Catalog</a>' +
        '</div>';
    }
  })
  .catch(function(err) {
    content.innerHTML = '<div style="text-align: center; padding: 30px; color: #EF4444;">' +
      '<p>Failed to query similar records. Please try again.</p>' +
      '</div>';
  });
}

function closeAiModal() {
  var modal = document.getElementById('aiSimilarModal');
  if (modal) {
    modal.style.display = 'none';
    document.body.style.overflow = '';
  }
}

document.addEventListener('click', function(e) {
  var target = e.target.closest('.btn-ai-mode');
  if (target) {
    e.preventDefault();
    e.stopPropagation();
    var pId = target.getAttribute('data-product-id');
    if (pId) {
      openAiModal(pId);
    }
  }

  var backdrop = document.getElementById('aiSimilarModal');
  if (backdrop && e.target === backdrop) {
    closeAiModal();
  }
});

document.addEventListener('keydown', function(e) {
  if (e.key === 'Escape') {
    closeAiModal();
  }
});

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', initCarousels);
} else {
  initCarousels();
}
